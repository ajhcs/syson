#!/usr/bin/env python3
"""Generate metadata only from pinned Git blobs; no imported project code executes.

Only stdlib. git show is read-only; the only write is this crate's generated.rs.
--check compares expected bytes without writing. No network or subprocess builds.
"""
# Copyright (c) 2024, 2026 Obeo.
# SPDX-License-Identifier: EPL-2.0
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import sys
import xml.etree.ElementTree as ET

BASELINE = "6ba2ac64e6b16ee2b05752ad55395eebb87d4910"
SOURCES = [
    ("Domain", "backend/metamodel/syson-sysml-metamodel/src/main/resources/model/sysml.ecore"),
    ("CustomNodes", "backend/metamodel/syson-siriusweb-customnodes-metamodel/src/main/resources/model/sysml-customnodes.ecore"),
]
ROOT = Path(__file__).resolve().parents[4]
OUTPUT = Path(__file__).resolve().parents[1] / "src" / "generated.rs"
XSI = "{http://www.w3.org/2001/XMLSchema-instance}type"


def string(value):
    # All pinned XML metadata is ASCII. Reject future control/non-ASCII instead
    # of emitting Python/JSON escapes that are not valid Rust syntax.
    if any(ord(c) < 32 or ord(c) > 126 for c in value):
        raise ValueError("unexpected non-ASCII metadata; review Rust escaping")
    return json.dumps(value)


def node(element):
    attrs = ",".join("(" + string(k) + "," + string(v) + ")" for k, v in sorted(element.attrib.items()))
    children = ",".join(node(child) for child in element)
    if element.text and element.text.strip():
        raise ValueError("unexpected XML text; metadata must not be discarded")
    return "MetadataNode { tag: " + string(element.tag) + ", attributes: &[" + attrs + "], children: &[" + children + "] }"


def generate():
    packages = []
    all_names = set()
    for package, path in SOURCES:
        raw = subprocess.run(["git", "show", BASELINE + ":" + path], cwd=ROOT,
                             check=True, stdout=subprocess.PIPE).stdout
        root = ET.fromstring(raw)
        for classifier in root:
            if classifier.tag != "eClassifiers":
                raise ValueError("unexpected package child")
            name = classifier.attrib["name"]
            if not name.isidentifier() or name in all_names:
                raise ValueError("ambiguous/invalid classifier identifier")
            all_names.add(name)
        packages.append((package, path, hashlib.sha256(raw).hexdigest(), root))
    lines = ["// Copyright (c) 2024, 2026 Obeo.", "// SPDX-License-Identifier: EPL-2.0",
             "// GENERATED by tools/generate.py from pinned upstream Git blobs. DO NOT EDIT.",
             "// Metadata only; handwritten semantic operations are not generated.", "use super::*;", "",
             "#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]",
             "#[rustfmt::skip]", "pub enum ClassifierId { " + ", ".join(c.attrib["name"] for _, _, _, r in packages for c in r) + " }", "",
             "#[rustfmt::skip]", "pub static SOURCES: &[Source] = &["]
    for package, path, digest, root in packages:
        lines.append("Source { package: Package::" + package + ", path: " + string(path) +
                     ", revision: " + string(BASELINE) + ", sha256: " + string(digest) +
                     ", attributes: &[" + ",".join("(" + string(k) + "," + string(v) + ")" for k, v in sorted(root.attrib.items())) + "] },")
    lines.extend(["];", ""])
    for package, _, _, root in packages:
        symbol = "DOMAIN_CLASSIFIERS" if package == "Domain" else "CUSTOM_NODE_CLASSIFIERS"
        lines.extend(["#[rustfmt::skip]", "pub static " + symbol + ": &[Classifier] = &["])
        for classifier in root:
            kind = {"ecore:EClass": "Class", "ecore:EEnum": "Enum"}.get(classifier.attrib[XSI])
            if kind is None:
                raise ValueError("unsupported classifier kind")
            name = classifier.attrib["name"]
            lines.append("Classifier { id: ClassifierId::" + name + ", package: Package::" + package +
                         ", kind: ClassifierKind::" + kind + ", node: " + node(classifier) + " },")
        lines.extend(["];", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != expected:
            print("generated metadata is stale", file=sys.stderr)
            return 1
    else:
        OUTPUT.write_text(expected)
    return 0


if __name__ == "__main__":
    sys.exit(main())
